/// The normative layout from `install-and-update.md` §2. The home page carries the short
/// form of the same tree; this is the longer one, because the two extra lines — the
/// manifest and the installer — are what the verification section below is about.
const String _installRoot = r'''
~/.alterione/                        # $ALTERIONE_HOME, default ~/.alterione
├── alterione                        # launcher — executable, add this directory to PATH
├── alterione-update                 # update
├── install.sh | install.ps1 | install.cmd
├── alterione.aot                    # the compiled release
├── alterione.yaml                   # the shipped manifest: runtime, api, extensions
├── manifest.json                    # versions, SHA-256 digests, signatures
├── bin/
│   └── dartrantime                  # the pinned AOT runtime, downloaded at install time
├── apps/                            # mirrors the source subprojects
│   └── cli/
├── tools/                           # Tier 2 tool executables and Tier 0 data
├── injections/                      # Tier 0 skill packs, Tier 2 injection executables
├── plugins/                         # Tier 2 plugin executables
├── config/                          # profiles/, policies.d/, config.yaml
├── state/                           # runtime state
└── logs/
''';

const String _launcher = r'''
#!/bin/sh
# alterione — generated by the installer. Runs the compiled release on the pinned runtime.
set -eu
home=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
[ -n "${ALTERIONE_HOME:-}" ] && home="$ALTERIONE_HOME"
exec "$home/bin/dartrantime" "$home/alterione.aot" "$@"
''';

/// The launch-time checks from `install-and-update.md` §5, as (subject, what is checked,
