/// A bordered data table. Local to this page rather than part of `ui.dart` because the
/// two uses have different column counts and different column semantics — one is check to
/// refusal, the other is source to product — and a shared helper for two unrelated shapes
/// would be a helper for neither.
Component _table(
  List<String> headers,
  List<List<Component>> rows,
) => div(classes: 'overflow-x-auto rounded-xl border border-line', [
  table(classes: 'w-full min-w-[38rem] border-collapse text-left', [
    thead([
      for (final header in headers)
        th(
          classes:
              'bg-canvas-subtle px-5 py-3 font-mono text-xs tracking-[0.14em] '
              'text-ink-muted uppercase',
          [.text(header)],
        ),
    ]),
    tbody(classes: 'divide-y divide-line', [
      for (final row in rows)
        tr([
          for (final cell in row) td(classes: 'px-5 py-4 align-top', [cell]),
        ]),
    ]),
  ]),
]);

