// The install page.
//
// This is the page most able to break a promise, because it is the page a reader arrives
// from a search result with the intention of running a command. Nothing is released: there
// is no install.sh in the tree, `alterione` is not on pub.dev, and every command printed
// here is labelled as the target shape before it is shown.
//
// The target is summarised from the "Installing" section of `README.md`,
// `docs/architecture/install-and-update.md`, `docs/architecture/build-and-release.md`,
// ADR-0016 and ADR-0017. Where a document shows a script, a layout or a table it is
// reproduced and attributed. Where none exists — an `alterione version` line, a doctor
// transcript — none is invented: a plausible-looking output block on a page like this is
// the one thing a reader has no way to check.

